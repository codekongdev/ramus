from __future__ import annotations

from collections.abc import Callable
from contextlib import AbstractContextManager
from typing import Protocol


class AccessPort(Protocol):
    def credentials(self, email: str) -> dict | None: ...
    def add_session(self, hashed_token: str, user_id: str, expires_at: str) -> None: ...
    def user_for_session(self, hashed_token: str, now: str) -> dict | None: ...
    def delete_session(self, hashed_token: str) -> None: ...
    def ensure_member(self, user_id: str, project_id: str) -> dict: ...
    def projects(self, user_id: str) -> list[dict]: ...
    def members(self, project_id: str) -> list[dict]: ...
    def allocate_sequence(self, project_id: str) -> int: ...
    def create_project(self, data: dict, members: list[dict]) -> None: ...
    def add_user(self, data: dict) -> None: ...


class ConversationPort(Protocol):
    def conversations(self, project_id: str) -> list[dict]: ...
    def messages(self, project_id: str) -> list[dict]: ...
    def conversation(self, ident: str, project_id: str) -> dict: ...
    def add_conversation(self, data: dict) -> dict: ...
    def add_message(self, data: dict) -> dict: ...


class WorkContext(Protocol):
    access: AccessPort
    conversations: ConversationPort


class UnitOfWork(Protocol):
    def transaction(self) -> AbstractContextManager[WorkContext]: ...
    def execute_once(
        self,
        actor_id: str,
        scope: str,
        request_id: str,
        payload: dict,
        operation: Callable[[WorkContext], dict],
        authorize: Callable[[WorkContext], None] | None = None,
        authorize_response: Callable[[WorkContext, dict], None] | None = None,
    ) -> dict: ...
