import { randomUUID } from 'node:crypto';
import { test, expect, signInAccount, TEST_PASSWORD } from './fixtures';

test('a legacy session sets its first password and returns to the same account after logout', async ({ page, testServer }) => {
  const { email, sessionToken } = testServer.legacyAccount;
  await page.context().addCookies([{ name: 'ramus_session', value: sessionToken, url: testServer.url, httpOnly: true, sameSite: 'Lax' }]);
  await page.goto('/');
  await expect(page.locator('.app-shell')).toBeVisible();
  const before = await (await page.request.get('/api/me')).json();
  expect(await (await page.request.get('/api/me/password')).json()).toEqual({ configured: false });
  const setup = page.getByRole('button', { name: '비밀번호 설정', exact: true });
  await setup.click();
  const dialog = page.getByRole('dialog', { name: '비밀번호 설정', exact: true });
  const password = dialog.getByLabel('새 비밀번호', { exact: true });
  const confirm = dialog.getByLabel('새 비밀번호 확인', { exact: true });
  await expect(password).toHaveAttribute('autocomplete', 'new-password');
  await page.setViewportSize({ width: 375, height: 812 });
  const box = await dialog.boundingBox();
  expect(box && box.x >= 0 && box.x + box.width <= 375).toBe(true);
  await page.screenshot({ path: 'artifacts/password-setup-mobile.png' });
  await page.setViewportSize({ width: 1280, height: 720 });
  await password.fill(TEST_PASSWORD);
  await confirm.fill('Other-password-2026');
  await dialog.getByRole('button', { name: '비밀번호 저장', exact: true }).click();
  await expect(dialog.getByRole('alert').filter({ hasText: '비밀번호가 일치하지 않습니다.' })).toBeVisible();
  await dialog.getByRole('button', { name: '취소', exact: true }).click();
  await setup.click();
  await expect(password).toHaveValue('');
  await expect(confirm).toHaveValue('');
  await password.fill(TEST_PASSWORD);
  await confirm.fill(TEST_PASSWORD);
  await dialog.getByRole('button', { name: '비밀번호 저장', exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect(setup).toHaveCount(0);
  expect(await (await page.request.get('/api/me/password')).json()).toEqual({ configured: true });
  const overwrite = await page.request.put('/api/me/password', { headers: { 'Idempotency-Key': randomUUID() }, data: { password: 'Replacement-password-2026' } });
  expect(overwrite.status()).toBe(409);
  await page.getByRole('button', { name: '로그아웃', exact: true }).click();
  await expect(page.getByLabel('이메일', { exact: true })).toBeVisible();
  expect((await page.request.get('/api/me/password')).status()).toBe(401);
  await signInAccount(page, email);
  const after = await (await page.request.get('/api/me')).json();
  expect(after).toEqual(before);
  await expect(setup).toHaveCount(0);
  expect(await page.evaluate(() => [JSON.stringify(localStorage), JSON.stringify(sessionStorage)])).toEqual(['{}', '{}']);
});
